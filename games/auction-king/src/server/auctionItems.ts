export function randomItems(count: number, usedIds: string[]): AuctionItem[] {
  const available = auctionItems.filter((item) => !usedIds.includes(item.id));
  const pool = available.length >= count ? available : auctionItems;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

